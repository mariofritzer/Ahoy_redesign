def to_xbm(art):
    rows = [r for r in art.strip("\n").split("\n")]
    w = len(rows[0])
    assert all(len(r) == w for r in rows), "uneven rows"
    h = len(rows)
    data = []
    for r in rows:
        for bx in range(0, w, 8):
            b = 0
            for bit in range(8):
                x = bx + bit
                if x < w and r[x] == "#":
                    b |= 1 << bit
            data.append(b)
    return w, h, data


def main():
    out = [
        "//-----------------------------------------------------------------------------",
        "// Icons for the modern 128x64 layout (generated by tools/display_icons/make_icons.py)",
        "//-----------------------------------------------------------------------------",
        "#pragma once",
        "#include <stdint.h>",
        "#include <U8g2lib.h>",
        "",
    ]
    for name, art in ICONS.items():
        w, h, data = to_xbm(art)
        out.append(f"#define ICON_{name.upper()}_W {w}")
        out.append(f"#define ICON_{name.upper()}_H {h}")
        hexs = ", ".join(f"0x{b:02x}" for b in data)
        out.append(f"static const uint8_t icon_{name}[] U8X8_PROGMEM = {{ {hexs} }};")
        out.append("")
    here = os.path.dirname(os.path.abspath(__file__))
    target = os.path.join(here, "..", "..", "src", "plugins", "Display", "Display_icons.h")
    with open(target, "w") as f:
        f.write("\n".join(out))
    print("written", os.path.normpath(target))


if __name__ == "__main__":
    main()
